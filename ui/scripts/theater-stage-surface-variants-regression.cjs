// node scripts/theater-stage-surface-variants-regression.cjs
// Reuse the existing TypeScript loader and webpage/store/sync regressions.
require('./theater-stage-surface-embeds-regression.cjs')
const assert = require('node:assert/strict')
const { createTheaterStageStore } = require('../src/views/theater/stage/StageStore.ts')
const { surfaceVariantsFor, normalizeSurfaceVariants, normalizeSurfaceTransition } = require('../src/views/theater/shared/stage-surface-variants.ts')
const { theaterSyncTesting: sync, TheaterSyncClient } = require('../src/views/theater/sync/TheaterSyncClient.ts')
const { stageSceneReadResultSchema } = require('../src/views/theater/bridge/theater-bridge-protocol.ts')
const { createSurfaceTransitionController } = require('../src/views/theater/stage/stage-surface-transition.ts')
const { stageSurfaceTransitionFrame, stageSceneTransitionKeyframes } = require('../src/views/theater/stage/stage-scene-transition.ts')
const { resolveTheaterStageMediaLocation } = require('../src/views/theater/stage/stage-media.ts')
const { createDefaultMediaFxSpec } = require('../src/features/media-fx/media-fx.ts')
const image = (id, mimeType = 'image/png') => ({ resourceId: id, url: `https://example.com/${id}`, mimeType })
const store = createTheaterStageStore()
const legacy = store.getSnapshot()
legacy.liveState.background = image('legacy-bg')
legacy.liveState.foreground = image('legacy-fg')
store.replaceState(legacy)
assert.equal(store.state.liveState.surfaceVariants, undefined)
assert.equal(surfaceVariantsFor(store.state.liveState, 'background').slots[0].image.resourceId, 'legacy-bg')
assert.equal(surfaceVariantsFor(store.state.liveState, 'foreground').activeId, 'default-foreground')
assert.equal(sync.documentFromWorkspace(store.getSnapshot()).liveState.surfaceVariants, undefined, 'read does not migrate legacy scenes')
const operate = (target, op) => assert.equal(store.operateSurfaceVariant(target, op), true)
const group = target => surfaceVariantsFor(store.state.liveState, target)
const fg = JSON.stringify(store.state.liveState.foreground)
const objects = JSON.stringify(store.state.liveState.sceneObjects)
const camera = JSON.stringify(store.state.camera)
const grid = store.state.liveState.displayGrid
store.setSceneSurfaceEmbed('background', { type: 'iframe', iframe: { url: 'https://example.com/page', scale: 1 }, interactive: true })
const fx = createDefaultMediaFxSpec()
fx.motion.preset = 'breathe'
fx.filter.saturation = 0.6
store.patchSceneSurfaceStyle('background', { opacity: 0.75, mediaFx: fx })
const shared = JSON.stringify([store.state.liveState.surfaceEmbeds, store.state.liveState.surfaceStyles])
operate('background', { type: 'add', id: 'rain', name: '雨天', image: image('rain') })
assert.equal(group('background').slots.length, 2)
assert.equal(group('background').activeId, 'rain')
operate('background', { type: 'copy', id: 'rain', newId: 'night' })
operate('background', { type: 'rename', id: 'night', name: '夜晚' })
operate('background', { type: 'replace', id: 'night', image: image('night') })
assert.equal(group('background').slots.find(slot => slot.id === 'rain').image.resourceId, 'rain')
assert.equal(store.state.liveState.background.resourceId, 'night')
assert.equal(JSON.stringify(store.state.liveState.foreground), fg)
assert.equal(JSON.stringify(store.state.liveState.sceneObjects), objects)
assert.equal(JSON.stringify(store.state.camera), camera)
assert.equal(store.state.liveState.displayGrid, grid)
assert.equal(JSON.stringify([store.state.liveState.surfaceEmbeds, store.state.liveState.surfaceStyles]), shared)
operate('background', { type: 'replace', id: 'night', image: null })
assert.equal(group('background').slots.length, 3, 'clear retains the slot')
assert.equal(group('background').activeId, 'night')
assert.equal(store.state.liveState.background, null)
operate('background', { type: 'delete', id: 'night' })
assert.ok(store.state.liveState.background, 'deleting the active slot selects a valid remaining image')
assert.equal(store.operateSurfaceVariant('background', { type: 'select', id: 'missing' }), false)
const beforeInvalid = store.getSnapshot()
assert.equal(store.operateSurfaceVariant('background', { type: 'add', id: 'invalid', name: '损坏', image: { resourceId: 'bad', url: 'javascript:alert(1)' } }), false)
assert.deepEqual(store.getSnapshot(), beforeInvalid)
operate('foreground', { type: 'select', id: null })
assert.equal(store.state.liveState.foreground, null)
assert.equal(group('foreground').slots[0].image.resourceId, 'legacy-fg')
operate('foreground', { type: 'select', id: 'default-foreground' })
assert.equal(store.state.liveState.foreground.resourceId, 'legacy-fg')
operate('background', { type: 'transition', patch: { type: 'slide', durationMs: 500 } })
assert.deepEqual(group('foreground').transition, { type: 'fade', durationMs: 350 })
const saved = store.getSnapshot()
const document = sync.documentFromWorkspace(saved)
const restored = sync.workspaceFromDocument(sync.normalizeDocument(JSON.parse(JSON.stringify(document))))
assert.deepEqual(restored.liveState.surfaceVariants, saved.liveState.surfaceVariants)
assert.deepEqual(stageSceneReadResultSchema.parse({ ok: true, state: restored }).state.liveState.surfaceVariants, saved.liveState.surfaceVariants)
const reloaded = createTheaterStageStore()
reloaded.replaceState(restored)
assert.equal(reloaded.surfaceChanges.background, 0, 'restoration does not request an animation')
const remote = JSON.parse(JSON.stringify(restored))
remote.liveState.surfaceVariants.background.activeId = 'rain'
remote.liveState.background = image('rain')
reloaded.replaceState(remote, true)
assert.equal(reloaded.surfaceChanges.background, 1, 'live peer mutation requests a local animation')
reloaded.replaceState(restored)
assert.equal(reloaded.surfaceChanges.background, 1, 'reconnect remains a reset')
const client = new TheaterSyncClient({ worldId: 'world', channelId: 'channel', store: reloaded })
const reloads = []
client.reload = async (...args) => { reloads.push(args) }
const gatewayEvent = { theater: { worldId: 'world', channelId: 'channel', revision: 1 } }
client.onGatewayEvent(gatewayEvent)
assert.equal(reloads.at(-1)[4], false, 'snapshot recovery has no surface animation intent')
client.onGatewayMutation(gatewayEvent)
assert.equal(reloads.at(-1)[4], true, 'live peer mutation has surface animation intent')
client.onGatewayConnected()
assert.equal(client.pendingSurfaceRevision, 0, 'reconnect drops pending animation intent')
assert.equal(client.surfaceAnimationEpoch, 1, 'reconnect invalidates in-flight animation intent')
const sourceId = store.state.activeSceneId
const { sceneId } = store.duplicateScene()
assert.deepEqual(store.state.scenes[sceneId].state.surfaceVariants, saved.liveState.surfaceVariants)
operate('background', { type: 'rename', id: 'rain', name: '副本雨天' })
assert.equal(store.state.scenes[sourceId].state.surfaceVariants.background.slots.find(slot => slot.id === 'rain').name, '雨天')
for (const slot of [...group('background').slots]) operate('background', { type: 'delete', id: slot.id })
assert.equal(store.state.liveState.background, null)
assert.equal(group('background').activeId, null)
assert.equal(group('foreground').slots.length, 1)
assert.deepEqual(normalizeSurfaceTransition({ type: 'bogus', durationMs: -1 }), { type: 'fade', durationMs: 20 })
assert.equal(normalizeSurfaceTransition({ durationMs: Infinity }).durationMs, 350)
assert.equal(normalizeSurfaceTransition({ durationMs: 99999 }).durationMs, 5000)
assert.equal(normalizeSurfaceVariants({ slots: [{ id: 'a', image: image('a') }, { id: 'a' }, { id: '' }], activeId: 'bad' }).slots.length, 1)
assert.equal(normalizeSurfaceVariants({ slots: [{ id: 'a', image: { url: 'javascript:alert(1)' } }], activeId: 'a' }).slots[0].image, null)
const normalizedStore = createTheaterStageStore()
normalizedStore.setSceneImage('background', image('legacy').url)
normalizedStore.operateSurfaceVariant('background', { type: 'add', id: ' padded ', name: 'trimmed', image: image('padded') })
assert.equal(normalizedStore.state.liveState.surfaceVariants.background.activeId, 'padded')
assert.equal(normalizedStore.state.liveState.background.resourceId, 'padded')
normalizedStore.operateSurfaceVariant('background', { type: 'copy', id: 'padded', newId: ' copied ' })
assert.equal(normalizedStore.state.liveState.surfaceVariants.background.activeId, 'copied')

// Failure rollback restores the entire previous slot state, including replacement edits.
const rollbackStore = createTheaterStageStore()
rollbackStore.operateSurfaceVariant('background', { type: 'add', id: 'day', name: '白天', image: image('day') })
rollbackStore.operateSurfaceVariant('background', { type: 'add', id: 'night', name: '夜晚', image: image('night') })
assert.equal(rollbackStore.rollbackFailedSurfaceVariant('background', image('night')), true)
assert.equal(rollbackStore.state.liveState.background.resourceId, 'day')
rollbackStore.operateSurfaceVariant('background', { type: 'replace', id: 'day', image: image('broken') })
assert.equal(rollbackStore.rollbackFailedSurfaceVariant('background', image('broken')), true)
assert.equal(rollbackStore.state.liveState.background.resourceId, 'day')
rollbackStore.operateSurfaceVariant('background', { type: 'replace', id: 'day', image: image('slow') })
rollbackStore.operateSurfaceVariant('background', { type: 'replace', id: 'day', image: image('newest') })
assert.equal(rollbackStore.rollbackFailedSurfaceVariant('background', image('slow')), false, 'stale failure cannot rollback a newer edit')
assert.equal(rollbackStore.state.liveState.background.resourceId, 'newest')
const urlOnly = normalizeSurfaceVariants({ slots: [{ id: 'remote', name: '远程', image: { url: 'https://example.com/img' } }], activeId: 'remote' })
assert.equal(urlOnly.slots[0].image.resourceId, '', 'normalization must not invent a resource id')
assert.deepEqual(urlOnly, normalizeSurfaceVariants(urlOnly), 'normalization is deterministic')

// Actual controller lifecycle: unready targets, stale callbacks, rapid switches,
// completion, cancellation and immediate/reduced-motion completion.
const disposed = [], stopped = []
const controller = createSurfaceTransitionController(item => disposed.push(item))
let current = 'initial', finish
const commit = item => { current = item }
const animate = (old, next, done) => { finish = done; return () => stopped.push(next) }
const stale = controller.begin('slow')
const fresh = controller.begin('fast')
assert.deepEqual(disposed, ['slow'])
assert.equal(controller.ready(stale, current, commit, animate), false)
assert.equal(current, 'initial')
assert.equal(controller.ready(fresh, current, commit, animate), true)
assert.equal(current, 'fast')
const next = controller.begin('newest')
assert.deepEqual(disposed, ['slow', 'initial'])
assert.deepEqual(stopped, ['fast'])
finish()
controller.failed(next)
assert.deepEqual(disposed, ['slow', 'initial', 'newest'])
const last = controller.begin('final')
controller.ready(last, current, commit, animate)
finish(); finish(); controller.cancel()
assert.equal(disposed.filter(item => item === 'fast').length, 1)
assert.equal(current, 'final')
const instant = controller.begin('instant')
controller.ready(instant, current, commit, (old, next, done) => { done(); return () => stopped.push('instant') })
assert.equal(controller.busy, false)
assert.equal(disposed.filter(item => item === 'final').length, 1)
assert.ok(stopped.includes('instant'))
for (const type of ['fade', 'slide', 'zoom', 'blur', 'dissolve']) {
  assert.equal(stageSurfaceTransitionFrame({ type, durationMs: 350 }, 'enter', 1).opacity, 1)
  assert.equal(stageSurfaceTransitionFrame({ type, durationMs: 350 }, 'exit', 1).opacity, 0)
  assert.ok(stageSceneTransitionKeyframes({ type, durationMs: 350 }, 'enter').length)
}
for (const mimeType of ['image/apng', 'image/gif', 'image/webp', 'video/webm']) {
  const ref = { ...image(mimeType.replace('/', '-'), mimeType), animated: true, loopCount: 3 }
  operate('background', { type: 'add', id: mimeType, name: mimeType, image: ref })
  assert.deepEqual(store.getSnapshot().liveState.background, ref)
  assert.deepEqual(stageSceneReadResultSchema.parse({ ok: true, state: store.getSnapshot() }).state.liveState.background, ref, 'Bridge preserves live media loop metadata')
  const media = resolveTheaterStageMediaLocation(ref, { urlBase: '', worldId: 'world', channelId: 'channel' })
  assert.equal(media.sourceKind, mimeType.startsWith('video/') ? 'video' : 'image')
}
console.log('surface variants: legacy, CRUD, independence, save/sync/Bridge/clone, live media and transition cleanup passed')
